package com.cooperative.model;

public class DashboardSummary {
    private int totalMembers;
    private int totalSocieties;
    private int totalVillageAreas;
    private int totalStaff;
    private int totalFunds;
    private int totalGroups;
    private int totalSavingsAccounts;
    private int totalLoans;
    private int totalRepayments;

    public DashboardSummary() {}

    public int getTotalMembers() { return totalMembers; }
    public void setTotalMembers(int totalMembers) { this.totalMembers = totalMembers; }

    public int getTotalSocieties() { return totalSocieties; }
    public void setTotalSocieties(int totalSocieties) { this.totalSocieties = totalSocieties; }

    public int getTotalVillageAreas() { return totalVillageAreas; }
    public void setTotalVillageAreas(int totalVillageAreas) { this.totalVillageAreas = totalVillageAreas; }

    public int getTotalStaff() { return totalStaff; }
    public void setTotalStaff(int totalStaff) { this.totalStaff = totalStaff; }

    public int getTotalFunds() { return totalFunds; }
    public void setTotalFunds(int totalFunds) { this.totalFunds = totalFunds; }

    public int getTotalGroups() { return totalGroups; }
    public void setTotalGroups(int totalGroups) { this.totalGroups = totalGroups; }

    public int getTotalSavingsAccounts() { return totalSavingsAccounts; }
    public void setTotalSavingsAccounts(int totalSavingsAccounts) { this.totalSavingsAccounts = totalSavingsAccounts; }

    public int getTotalLoans() { return totalLoans; }
    public void setTotalLoans(int totalLoans) { this.totalLoans = totalLoans; }

    public int getTotalRepayments() { return totalRepayments; }
    public void setTotalRepayments(int totalRepayments) { this.totalRepayments = totalRepayments; }
}
